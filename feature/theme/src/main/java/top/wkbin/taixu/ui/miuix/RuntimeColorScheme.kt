/**
 * HyperOS keeps every surface neutral and lets only the accent follow the palette; tonal M3
 * surfaces (tinted pages, cards and containers) are what make a seeded or Monet scheme read as
 * Material. Surfaces are therefore always taken from the miuix neutral ladder — page `surface`,
 * card `surfaceContainer`, nested fills stepping toward the foreground — and every accent
 * container (the M3 selection/highlight roles) becomes the miuix light tint of `primary` with
 * `primary` content. Neutral fills inside cards use `surfaceContainerHigh`.
 */
internal fun ColorScheme.withMiuixSurfaces(dark: Boolean): ColorScheme {
    val base = if (dark) defaultDarkColors else defaultLightColors
    val page = base.surface
    val card = base.surfaceContainer
    val fg = base.onSurface
    val high = lerp(card, fg, if (dark) 0.07f else 0.05f)
    val highest = lerp(card, fg, if (dark) 0.12f else 0.09f)
    val accentFill = lerp(card, primary, if (dark) 0.22f else 0.10f)
    return copy(
        primaryContainer = accentFill,
        onPrimaryContainer = primary,
        secondaryContainer = accentFill,
        onSecondaryContainer = primary,
        tertiaryContainer = accentFill,
        onTertiaryContainer = primary,
        background = page,
        onBackground = fg,
        surface = page,
        onSurface = fg,
        surfaceVariant = highest,
        onSurfaceVariant = lerp(card, fg, if (dark) 0.55f else 0.6f),
        surfaceContainerLowest = card,
        surfaceContainerLow = card,
        surfaceContainer = card,
        surfaceContainerHigh = high,
        surfaceContainerHighest = highest,
        outline = base.outline,
        outlineVariant = base.dividerLine,
        inverseSurface = fg,
        inverseOnSurface = page,
        surfaceBright = card,
        surfaceDim = page,
    )
}

/** Maps an already neutralized scheme onto miuix; neutral roles stay on miuix's own defaults. */
internal fun ColorScheme.toMiuixColors(dark: Boolean): Colors {
    val base = if (dark) top.yukonga.miuix.kmp.theme.darkColorScheme() else top.yukonga.miuix.kmp.theme.lightColorScheme()
    return base.copy(
        primary = primary,
        onPrimary = onPrimary,
        primaryVariant = primary,
        onPrimaryVariant = onPrimary,
        primaryContainer = primary,
        onPrimaryContainer = onPrimary,
        tertiaryContainer = tertiaryContainer,
        onTertiaryContainer = onTertiaryContainer,
        onBackgroundVariant = onSurfaceVariant,
        error = error,
        onError = onError,
        errorContainer = errorContainer,
        onErrorContainer = onErrorContainer,
        disabledPrimary = primary.copy(alpha = 0.38f),
        disabledPrimaryButton = primary.copy(alpha = 0.38f),
        disabledPrimarySlider = primary.copy(alpha = 0.38f),
    )
}

